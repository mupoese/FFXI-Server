    def _update_individual_npc_behavior(self, npc_id: int):
        """Update individual NPC behavior based on interactions."""
        try:
            with sqlite3.connect(self.db_path) as conn:
                # Get recent interactions
                interactions = conn.execute(
                    """
                    SELECT player_id, interaction_type, success_rate, satisfaction_score
                    FROM player_interactions 
                    WHERE npc_id = ? AND timestamp > datetime('now', '-7 days')
                """,
                    (npc_id,),
                ).fetchall()

                if not interactions:
                    return

                # Calculate interaction statistics
                avg_satisfaction = sum(i[3] for i in interactions) / len(interactions)
                interaction_types = [i[1] for i in interactions]
                most_common_interaction = max(
                    set(interaction_types), key=interaction_types.count
                )

                # Load or create NPC behavior
                npc_behavior = self._load_npc_behavior(npc_id)

                # Update behavior based on interaction success
                if avg_satisfaction > 0.7:
                    # Positive interactions - maintain current personality
                    npc_behavior.story_involvement = min(
                        1.0, npc_behavior.story_involvement + 0.1
                    )
                elif avg_satisfaction < 0.3:
                    # Negative interactions - adjust personality
                    if "helpfulness" in npc_behavior.personality_traits:
                        npc_behavior.personality_traits["helpfulness"] *= 0.9

                # Update dialogue style based on interaction patterns
                if most_common_interaction == "trading":
                    npc_behavior.dialogue_style = "business"
                elif most_common_interaction == "combat":
                    npc_behavior.dialogue_style = "aggressive"
                elif most_common_interaction == "guidance":
                    npc_behavior.dialogue_style = "helpful"

                # Store updated behavior
                self._store_npc_behavior(npc_behavior)

        except Exception as e:
            self.logger.error(
                f"Individual NPC behavior update failed for NPC {npc_id}: {e}"
            )

