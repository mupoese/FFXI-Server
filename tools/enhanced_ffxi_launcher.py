class ServerConfig:
    """Manages server configuration with configurable branding"""
    
    def __init__(self, env_file: str = '.env'):
        self.env_file = env_file
        self.config = self.load_env_file()
        self.server_name = self.config.get('SERVERNAME', 'FFXI')
        
    def load_env_file(self) -> Dict[str, str]:
        """Load configuration from .env file"""
        config = {}
        env_path = Path(self.env_file)
        
        if not env_path.exists():
            logger.warning(f"Environment file {self.env_file} not found")
            return self.get_default_config()
        
        try:
            with open(env_path, 'r') as f:
                for line in f:
                    line = line.strip()
                    if line and not line.startswith('#') and '=' in line:
                        key, value = line.split('=', 1)
                        config[key.strip()] = value.strip().strip('"\'')
        except Exception as e:
            logger.error(f"Failed to load .env file: {e}")
            return self.get_default_config()
        
        return config
    
    def get_default_config(self) -> Dict[str, str]:
        """Get default configuration values"""
        server_name = 'FFXI'
        return {
            'SERVERNAME': server_name,
            f'{server_name}_SERVER_NAME': f'{server_name} Private Server',
            f'{server_name}_SERVER_HOST': 'localhost',
            f'{server_name}_LOGIN_PORT': '54001',
            f'{server_name}_MAP_PORT': '54230',
            f'{server_name}_SEARCH_PORT': '54002',
            f'{server_name}_CLIENT_PATH': '',
            f'{server_name}_WINDOWER_COMPATIBLE': 'true',
            f'{server_name}_ASHITA_COMPATIBLE': 'true',
            f'{server_name}_AUTO_UPDATE': 'true',
            f'{server_name}_CLIENT_TIMEOUT': '30000',
            f'{server_name}_API_SECRET_KEY': 'your_secret_key_here_change_this',
            f'{server_name}_ADMIN_USERNAME': 'admin',
            f'{server_name}_ADMIN_PASSWORD': 'admin123'
        }
    
    def get(self, key: str, default: str = '') -> str:
        """Get configuration value with server name prefix"""
        # Try with server name prefix first
        prefixed_key = f"{self.server_name}_{key}"
        if prefixed_key in self.config:
            return self.config[prefixed_key]
        
        # Fallback to original key
        return self.config.get(key, default)
    
    def set(self, key: str, value: str):
        """Set configuration value with server name prefix"""
        prefixed_key = f"{self.server_name}_{key}"
        self.config[prefixed_key] = value
    
    def save(self):
        """Save configuration back to .env file"""
        try:
            with open(self.env_file, 'w') as f:
                f.write(f"# {self.server_name} Server Configuration\n")
                f.write(f"# Generated by {self.server_name} Launcher on {datetime.now().isoformat()}\n\n")
                
                # Write SERVERNAME first
                f.write(f"SERVERNAME={self.server_name}\n\n")
                
                for key, value in sorted(self.config.items()):
                    if key != 'SERVERNAME':  # Skip SERVERNAME as it's already written
                        f.write(f"{key}={value}\n")
        except Exception as e:
            logger.error(f"Failed to save .env file: {e}")

class ServerAPIClient:
    """Client for communicating with server API"""
    
    def __init__(self, server_config: ServerConfig):
        self.config = server_config
        self.server_name = server_config.server_name
        self.base_url = f"http://{self.config.get('SERVER_HOST', 'localhost')}:5000"
        self.token = None
        
    def authenticate(self, username: str, password: str) -> Dict[str, Any]:
        """Authenticate with server API"""
        try:
            response = requests.post(
                f"{self.base_url}/auth/token",
                json={'username': username, 'password': password},
                timeout=10
            )
            
            if response.status_code == 200:
                data = response.json()
                self.token = data.get('token')
                return {'success': True, 'data': data}
            else:
                return {'success': False, 'error': response.json().get('error', 'Authentication failed')}
                
        except requests.exceptions.RequestException as e:
            return {'success': False, 'error': f'Connection failed: {str(e)}'}
    
    def get_server_status(self) -> Dict[str, Any]:
        """Get server status information"""
        if not self.token:
            return {'success': False, 'error': 'Not authenticated'}
        
        try:
            headers = {'Authorization': f'Bearer {self.token}'}
            response = requests.get(f"{self.base_url}/api/status", headers=headers, timeout=10)
            
            if response.status_code == 200:
                return {'success': True, 'data': response.json()}
            else:
                return {'success': False, 'error': 'Failed to get server status'}
                
        except requests.exceptions.RequestException as e:
            return {'success': False, 'error': f'Connection failed: {str(e)}'}
    
    def get_player_info(self) -> Dict[str, Any]:
        """Get player information (placeholder for future implementation)"""
        if not self.token:
            return {'success': False, 'error': 'Not authenticated'}
        
        # This would connect to actual player database
        return {
            'success': True, 
            'data': {
                'online_players': 42,
                'max_players': int(self.config.get('MAX_PLAYERS', '500')),
                'server_uptime': '2 days, 14 hours',
                'server_version': '1.0.0'
            }
        }

