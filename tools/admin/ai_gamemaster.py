    def _cleanup_expired_events(self):
        """Clean up expired events."""
        current_time = datetime.now()
        expired_events = []

        for event_id, event in self.active_events.items():
            end_time = event.start_time + timedelta(minutes=event.duration_minutes)
            if current_time > end_time:
                expired_events.append(event_id)

        for event_id in expired_events:
            del self.active_events[event_id]

    def start(self):
        """Start the AI Game Master system."""
        if self.running:
            self.logger.warning("AI Game Master already running")
            return

        self.running = True
        self.logger.info("Starting Advanced AI Game Master - Iteration 13")

        # Load initial data
        self.load_player_profiles()

        # Start processing threads
        threads = [
            threading.Thread(target=self.event_generation_loop),
            threading.Thread(target=self.player_analysis_loop),
            threading.Thread(target=self.npc_behavior_loop),
        ]

        for thread in threads:
            thread.daemon = True
            thread.start()
            self.threads.append(thread)

        self.logger.info("AI Game Master started successfully")

    def stop(self):
        """Stop the AI Game Master system."""
        self.logger.info("Stopping AI Game Master")
        self.running = False

        for thread in self.threads:
            thread.join(timeout=5)

        self.logger.info("AI Game Master stopped")

