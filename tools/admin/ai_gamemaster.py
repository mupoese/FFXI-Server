    def _optimize_player_experience(self, profile: PlayerProfile):
        """Optimize experience for individual player."""
        try:
            # Analyze player's recent activity
            with sqlite3.connect(self.db_path) as conn:
                recent_events = conn.execute(
                    """
                    SELECT event_id, satisfaction_score FROM player_interactions 
                    WHERE player_id = ? AND timestamp > datetime('now', '-7 days')
                """,
                    (profile.player_id,),
                ).fetchall()

                if not recent_events:
                    # New or inactive player - generate welcoming content
                    self._generate_welcome_content(profile)
                else:
                    avg_satisfaction = sum(r[1] for r in recent_events) / len(
                        recent_events
                    )

                    if avg_satisfaction < 0.4:
                        # Player is unsatisfied - adjust content difficulty
                        self._adjust_content_difficulty(profile, decrease=True)
                    elif avg_satisfaction > 0.8 and profile.challenge_preference > 0.6:
                        # Player wants more challenge
                        self._adjust_content_difficulty(profile, decrease=False)

        except Exception as e:
            self.logger.error(
                f"Player optimization failed for {profile.player_id}: {e}"
            )

