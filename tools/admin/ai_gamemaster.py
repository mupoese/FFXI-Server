    def _generate_event_id(self, event_type: EventType) -> str:
        """Generate unique event ID."""
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        type_code = event_type.value[:4].upper()
        random_suffix = hashlib.md5(
            f"{timestamp}{random.random()}".encode()
        ).hexdigest()[:6]
        return f"{type_code}_{timestamp}_{random_suffix}"

