    def _select_target_players(self, event_type: EventType) -> List[int]:
        """Select target players for the event based on preferences and engagement."""
        suitable_players = []

        for player_id, profile in self.player_profiles.items():
            # Check if player is active
            if (datetime.now() - profile.last_seen).total_seconds() > 7200:  # 2 hours
                continue

            # Check engagement score
            if profile.engagement_score < 0.3:
                continue

            # Check content preferences
            content_match = False
            if event_type.value in profile.preferred_content:
                content_match = True
            elif event_type in [EventType.SOCIAL_GATHERING, EventType.QUEST_CHAIN]:
                if profile.social_preference > 0.6:
                    content_match = True
            elif event_type in [EventType.INVASION, EventType.RARE_SPAWN]:
                if profile.challenge_preference > 0.5:
                    content_match = True

            if content_match:
                suitable_players.append(player_id)

        # Limit to reasonable number of players
        max_targets = min(20, len(suitable_players))
        if len(suitable_players) > max_targets:
            # Select highest engagement players
            suitable_players.sort(
                key=lambda pid: self.player_profiles[pid].engagement_score, reverse=True
            )
            suitable_players = suitable_players[:max_targets]

        return suitable_players

    def _calculate_adaptive_difficulty(
        self, target_players: List[int]
    ) -> DifficultyLevel:
        """Calculate adaptive difficulty based on target players."""
        if not target_players:
            return DifficultyLevel.MODERATE

        avg_skill = sum(
            self.player_profiles[pid].skill_rating for pid in target_players
        ) / len(target_players)
        avg_challenge_pref = sum(
            self.player_profiles[pid].challenge_preference for pid in target_players
        ) / len(target_players)

        # Combine skill and preference
        difficulty_score = avg_skill * 0.6 + avg_challenge_pref * 0.4

        if difficulty_score < 0.2:
            return DifficultyLevel.EASY
        elif difficulty_score < 0.4:
            return DifficultyLevel.MODERATE
        elif difficulty_score < 0.6:
            return DifficultyLevel.CHALLENGING
        elif difficulty_score < 0.8:
            return DifficultyLevel.HARD
        else:
            return DifficultyLevel.EXTREME

