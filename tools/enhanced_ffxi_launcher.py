    def check_server_status(self):
        """Check server status"""
        def check_status():
            self.log_message("Checking server status...")
            
            host = self.server_host_var.get() or 'localhost'
            login_port = self.login_port_var.get() or '54001'
            
            try:
                import socket
                sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
                sock.settimeout(5)
                result = sock.connect_ex((host, int(login_port)))
                sock.close()
                
                if result == 0:
                    self.log_message(f"✅ Server is online at {host}:{login_port}")
                else:
                    self.log_message(f"❌ Server is offline or unreachable at {host}:{login_port}")
            except Exception as e:
                self.log_message(f"❌ Failed to check server status: {e}")
        
        threading.Thread(target=check_status, daemon=True).start()
    
    def launch_client(self):
        """Launch client with Ashita"""
        def launch():
            self.log_message(f"Preparing to launch {self.server_name} client...")
            
            # Save current configuration
            self.save_current_config()
            
            # Generate temporary Ashita config
            temp_config_path = "temp_ashita_config.ini"
            if not self.ashita_generator.generate_config(temp_config_path):
                self.log_message("❌ Failed to generate Ashita configuration")
                return
            
            self.log_message("✅ Generated Ashita configuration")
            
            # Check for Ashita CLI
            ashita_cli_path = Path("ashita/Ashita-cli.exe")
            if not ashita_cli_path.exists():
                self.log_message("❌ Ashita CLI not found. Please ensure Ashita files are downloaded.")
                return
            
            try:
                # Launch Ashita with generated configuration
                cmd = [str(ashita_cli_path), "--config", temp_config_path]
                self.log_message(f"Launching: {' '.join(cmd)}")
                
                process = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
                
                # Read output
                stdout, stderr = process.communicate(timeout=30)
                
                if process.returncode == 0:
                    self.log_message("✅ Client launched successfully")
                    if stdout:
                        self.log_message(f"Output: {stdout}")
                else:
                    self.log_message(f"❌ Client launch failed (exit code: {process.returncode})")
                    if stderr:
                        self.log_message(f"Error: {stderr}")
                
            except subprocess.TimeoutExpired:
                self.log_message("⚠️ Launch command timed out (this may be normal)")
            except Exception as e:
                self.log_message(f"❌ Failed to launch client: {e}")
            finally:
                # Clean up temporary config
                if Path(temp_config_path).exists():
                    Path(temp_config_path).unlink()
        
        threading.Thread(target=launch, daemon=True).start()
    
    def log_message(self, message: str):
        """Add message to status log"""
        timestamp = datetime.now().strftime("%H:%M:%S")
        formatted_message = f"[{timestamp}] {message}\n"
        
        self.status_text.insert(tk.END, formatted_message)
        self.status_text.see(tk.END)
        self.root.update()
    
    def clear_log(self):
        """Clear the status log"""
        self.status_text.delete(1.0, tk.END)
    
    def run(self):
        """Run the GUI"""
        self.root.mainloop()

